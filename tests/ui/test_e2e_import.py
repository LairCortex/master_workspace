async def test_imported_world_persists_after_app_restart(app, file_dialogs, wait_for):
    """Spec «Данные сохраняются сразу»: import → explicit restart (shutdown →
    start on the same game file) → entities, links, ghost and types in the
    freshly opened game."""
    application, window = app
    db_path = application._db_path

    dialog = await _import_fixture_through_dialog(window, file_dialogs, wait_for)
    dialog.import_btn.click()  # «Импортировать»
    await wait_for(lambda: dialog.vm.state == "done")
    dialog.import_btn.click()  # «Закрыть»
    await wait_for(lambda: not dialog.isVisible())

    # Real restart: the game DB file is reopened through a brand-new engine.
    await application.shutdown()
    window2 = await application.start(str(db_path))
    try:
        names = [e.name for e in timeline_probe.events(window2)]
        assert len(names) == 2  # exactly the imported events, no leftovers
        assert set(names) == {"Поход каравана на восток", "Взятие Штурмграда"}

        assert query_db(db_path, "SELECT COUNT(*) FROM characters")[0][0] == 3
        assert query_db(db_path, "SELECT COUNT(*) FROM locations")[0][0] == 2
        assert query_db(db_path, "SELECT COUNT(*) FROM organizations")[0][0] == 1
        # 2 file items + the ghost «Амулет вдовы» with its referral-date span
        assert query_db(
            db_path,
            "SELECT start_date, end_date FROM items WHERE name = 'Амулет вдовы'",
        ) == [("1200-05-01", "1203-01-20")]
        # six NRI defaults + the two auto-created types
        assert query_db(db_path, "SELECT COUNT(*) FROM event_types")[0][0] == 8
        assert {
            name for (name,) in query_db(
                db_path, "SELECT name FROM event_types WHERE name IN ('Война','Поход')"
            )
        } == {"Война", "Поход"}
        # every link the report counted is in the file's associations
        assert query_db(db_path,
                        "SELECT COUNT(*) FROM event_character")[0][0] == 5
        assert query_db(db_path,
                        "SELECT COUNT(*) FROM event_item")[0][0] == 4
        assert query_db(db_path,
                        "SELECT COUNT(*) FROM event_location")[0][0] == 2
        assert query_db(db_path,
                        "SELECT COUNT(*) FROM event_organization")[0][0] == 1
        # the skipped rows stayed out of the committed world
        assert query_db(
            db_path, "SELECT COUNT(*) FROM events WHERE name = 'Пир в ратуше'"
        ) == [(0,)]
        assert query_db(
            db_path, "SELECT COUNT(*) FROM characters WHERE name = 'Гоблин-наёмник'"
        ) == [(0,)]
    finally:
        window.close()  # no-op for the already closed pre-restart window
        await application.shutdown()
